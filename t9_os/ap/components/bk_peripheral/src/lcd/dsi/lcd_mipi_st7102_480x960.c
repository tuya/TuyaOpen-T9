/**
 * @file lcd_mipi_st7102_480x960.c
 * @brief ST7102 MIPI DSI Panel Driver (480x960 native, 4-lane)
 *
 * BOE 4.94" TDDI panel with ST7102 driver IC. The panel scans natively in
 * portrait: 480 pixels per line, 960 lines. Init sequence from
 * ST7102_BOE_494_90hz_0823_VOP5V_G22_3ms.txt:
 *   mipi.dsi 4 500 burst
 *   mipi.video 960 480 60 10 215 40 40 2 2
 *
 * Panel timing is taken from the vendor DT timing node, which fixes the
 * axis assignment for the six values in the mipi.video line:
 *   clock-frequency = <40000000>; // (480+40+2+40)*(960+215+2+10)*60 = 40.03 MHz
 *   hactive 480, hfp  40, hsync 2, hbp  40
 *   vactive 960, vfp 215, vsync 2, vbp  10
 * The commented 91 Hz variant raises the vertical front porch from 215 to
 * 375 (Vtotal 1347, pclk ~68.89 MHz); this driver keeps fps = 60.
 */

